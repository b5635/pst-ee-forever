"""Every player spell of PST:EE (SPWI*/SPPR* with a TLK name) from the game files, for the spell suites.

  python -I tools/spell_list.py        writes tests/ingame/spell_list.lua and tests/unit/spell_table.h

Per spell: resref, BCS id (SPWI119 -> 2119, SPPR101 -> 1101), name, level, hostile flag, the suite caster's header target
type / range / projectile, and its effects (header 0 + global): opcode, timing, duration (s), target.
Re-run after a mod changes spells (PST-UB-Reloaded is installed); both outputs are committed.
"""
import os, re, struct, sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import ieres  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MAGE_LEVEL, PRIEST_LEVEL = 20, 14  # tests/ingame/tbc_spells_all.lua kMageLevel / kPriestLevel


def spells():
  ieres._key = ieres._key or ieres.load_key()
  names = sorted({n for (n, e) in ieres._key if e == "SPL" and re.fullmatch(r"SP(WI|PR)\d{3}", n)} |
                 {f.split(".")[0].upper() for f in os.listdir(os.path.join(ieres.GAME, "override"))
                  if re.fullmatch(r"SP(WI|PR)\d{3}\.SPL", f.upper())})
  out = []
  for n in names:
    d = ieres.read(n, "SPL")
    if not d or d[:4] != b"SPL ":
      continue
    name = ieres.tlk(struct.unpack_from("<I", d, 0x08)[0]).strip()
    if not name:
      continue
    flags = struct.unpack_from("<I", d, 0x18)[0]
    level = struct.unpack_from("<I", d, 0x34)[0]
    oext, next_, ofeat, ocast, ncast = struct.unpack_from("<IHIHH", d, 0x64)
    fx = []
    for i in range(ncast):
      fx.append(feature(d, ofeat + (ocast + i) * 0x30))
    target, rng, proj = 0, 0, 0
    # the ability header the all-spells suite's caster gets: the last one whose minimum level it has (the engine picks
    # the SPL ability for the caster level, CGameSprite::SpellPST); header 0 when it has none
    caster_level = MAGE_LEVEL if n.startswith("SPWI") else PRIEST_LEVEL
    hdr = 0
    for h in range(next_):
      if struct.unpack_from("<H", d, oext + h * 0x28 + 0x10)[0] <= caster_level:
        hdr = h
    if next_:
      o = oext + hdr * 0x28
      target, rng = d[o + 0x0C], struct.unpack_from("<H", d, o + 0x0E)[0]
      proj = struct.unpack_from("<H", d, o + 0x26)[0]
      cnt, first = struct.unpack_from("<HH", d, o + 0x1E)
      for i in range(cnt):
        fx.append(feature(d, ofeat + (first + i) * 0x30))
    sid = (2000 if n.startswith("SPWI") else 1000) + int(n[4:])
    out.append(dict(res=n, id=sid, name=name, level=level, hostile=1 if flags & 0x400 else 0, target=target,
                    range=rng, proj=proj, fx=fx))
  return out


def feature(d, o):
  op, tgt, _pw, _p1, _p2, tim, _r, dur = struct.unpack_from("<HBBIIBBI", d, o)
  return (op, tim, dur, tgt)


def main():
  sp = spells()
  lua = ["-- SPDX-License-Identifier: GPL-2.0-or-later",
         "-- Generated by tools/spell_list.py from the game files: every player spell (SPWI/SPPR with a name).",
         "-- {res, id, name, level, hostile, target type, range, projectile}",
         "pstfSpellList = {"]
  for s in sp:
    lua.append('\t{"%s", %d, %s, %d, %d, %d, %d, %d},' % (s["res"], s["id"], lua_str(s["name"]), s["level"], s["hostile"],
                                                         s["target"], s["range"], s["proj"]))
  lua.append("}")
  open(os.path.join(ROOT, "tests", "ingame", "spell_list.lua"), "w", newline="\n").write("\n".join(lua) + "\n")
  h = ["// SPDX-License-Identifier: GPL-2.0-or-later",
       "// Generated by tools/spell_list.py from the game files (PST:EE 3.2.2 + PST-UB-Reloaded): every player",
       "// spell's global effects and those of the ability header its suite caster uses (mage level 20, priest 14).",
       "// Do not edit; re-run the tool.",
       "#pragma once",
       "#include <cstdint>",
       "",
       "namespace pstf::spelltable {",
       "struct Fx {",
       "  uint16_t op;",
       "  uint8_t timing;    // SPL feature timing mode (0 duration, 1 permanent, 4 delayed->permanent, ...)",
       "  uint32_t duration; // seconds (timing 10: ticks)",
       "  uint8_t target;",
       "};",
       "struct Spell {",
       "  const char* res;",
       "  int id;           // BCS spell number",
       "  const char* name;",
       "  int level;",
       "  bool hostile;",
       "  int target, range, projectile;",
       "  int first, count; // into kFx",
       "};"]
  fxs, rows = [], []
  for s in sp:
    rows.append('    {"%s", %d, %s, %d, %s, %d, %d, %d, %d, %d},' % (s["res"], s["id"], c_str(s["name"]), s["level"],
                                                                   "true" if s["hostile"] else "false", s["target"],
                                                                   s["range"], s["proj"], len(fxs), len(s["fx"])))
    fxs += s["fx"]
  h.append("inline constexpr Fx kFx[] = {")
  for (op, tim, dur, tgt) in fxs:
    h.append("    {%d, %d, %d, %d}," % (op, tim, dur, tgt))
  h.append("};")
  h.append("inline constexpr Spell kSpells[] = {")
  h += rows
  h.append("};")
  h.append("}  // namespace pstf::spelltable")
  open(os.path.join(ROOT, "tests", "unit", "spell_table.h"), "w", newline="\n").write("\n".join(h) + "\n")
  print(f"spell_list: {len(sp)} spells, {len(fxs)} effects")


def lua_str(s):
  return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def c_str(s):
  return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


if __name__ == "__main__":
  main()
